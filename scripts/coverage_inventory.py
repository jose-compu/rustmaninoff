#!/usr/bin/env python3
"""Inventory rustmaninoff vs pinned Checkov CKV IDs for the fidelity table (#42).

Reads `tools/checkov-ids/snapshot.json` when present. Emits Markdown to stdout.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
POLICIES = ROOT / "crates" / "cli" / "policies"
SNAPSHOT = ROOT / "tools" / "checkov-ids" / "snapshot.json"

# Known intentional ID / semantics divergences (document, do not hide).
DIVERGENCES = [
    (
        "CKV_DOCKER_1",
        "Checkov: EXPOSE must not publish port 22. rustmaninoff: base image must not use `:latest` (Checkov’s CKV_DOCKER_7).",
    ),
    (
        "CKV_DOCKER_7",
        "Checkov: ReferenceLatestTag. Covered today under rustmaninoff CKV_DOCKER_1 (same intent, different id).",
    ),
    (
        "CKV_DOCKER_8",
        "Checkov: RootUser. Overlaps rustmaninoff CKV_DOCKER_3 (USER exists and is not root).",
    ),
]


def policy_ids() -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    for path in sorted(POLICIES.rglob("*.yaml")):
        rows.append((path.parent.name, path.stem))
    return rows


def family(check_id: str) -> str:
    if check_id.startswith("CKV2_"):
        return "CKV2"
    for prefix in ("CKV_AWS_", "CKV_AZURE_", "CKV_GCP_", "CKV_K8S_", "CKV_DOCKER_", "CKV_"):
        if check_id.startswith(prefix):
            return prefix.rstrip("_")
        if prefix != "CKV_" and check_id.startswith(prefix.rstrip("_") + "_"):
            return prefix.rstrip("_")
    return "other"


def load_snapshot() -> dict[str, list[str]] | None:
    if not SNAPSHOT.is_file():
        return None
    data = json.loads(SNAPSHOT.read_text())
    return {k: list(v) for k, v in data.get("ids", {}).items()}


def our_ids_by_claim() -> dict[str, set[str]]:
    """Map fidelity claim buckets to our policy ids."""
    rows = policy_ids()
    buckets: dict[str, set[str]] = defaultdict(set)
    for fw, cid in rows:
        if fw == "docker" or cid.startswith("CKV_DOCKER_"):
            buckets["docker"].add(cid)
        if fw == "kubernetes" or cid.startswith("CKV_K8S_"):
            buckets["kubernetes"].add(cid)
        if cid.startswith("CKV_AWS_") or cid.startswith("CKV2_AWS"):
            buckets["terraform_aws"].add(cid)
        if fw == "terraform":
            buckets["terraform_all"].add(cid)
        if fw == "cloudformation":
            buckets["cloudformation"].add(cid)
    return buckets


def pct(n: int, d: int) -> str:
    if d == 0:
        return "n/a"
    return f"{(100.0 * n / d):.1f}%"


def render_markdown(rows: list[tuple[str, str]], snapshot: dict[str, list[str]] | None) -> str:
    by_fw: dict[str, list[str]] = defaultdict(list)
    by_fam: dict[str, int] = defaultdict(int)
    for fw, cid in rows:
        by_fw[fw].append(cid)
        by_fam[family(cid)] += 1

    lines = [
        "# Checkov fidelity / coverage",
        "",
        f"Generated by `scripts/coverage_inventory.py` from `{POLICIES.relative_to(ROOT)}`",
        f"and `{SNAPSHOT.relative_to(ROOT)}` (when present).",
        "",
        f"**Built-in checks (rustmaninoff):** {len(rows)}",
        "",
        "## By framework directory",
        "",
        "| Framework | Count |",
        "| --- | ---: |",
    ]
    for fw in sorted(by_fw):
        lines.append(f"| {fw} | {len(by_fw[fw])} |")

    lines += [
        "",
        "## By CKV family",
        "",
        "| Family | Count |",
        "| --- | ---: |",
    ]
    for fam in sorted(by_fam):
        lines.append(f"| {fam} | {by_fam[fam]} |")

    if snapshot:
        ours = our_ids_by_claim()
        lines += [
            "",
            "## Coverage vs pinned Checkov catalog",
            "",
            "Denominator = Checkov check `id` values scraped from bridgecrewio/checkov (see snapshot meta).",
            "Numerator = exact id match in rustmaninoff builtins (same CKV string).",
            "",
            "| Claim surface | Checkov IDs | rustmaninoff exact | Coverage |",
            "| --- | ---: | ---: | ---: |",
        ]
        claims = [
            ("docker", "docker"),
            ("kubernetes", "kubernetes"),
            ("terraform AWS resource checks", "terraform_aws"),
        ]
        for label, key in claims:
            checkov = set(snapshot.get(key, []))
            have = ours.get(key, set()) & checkov
            lines.append(
                f"| {label} | {len(checkov)} | {len(have)} | {pct(len(have), len(checkov))} |"
            )

        # Missing samples (short)
        lines += ["", "## Sample gaps (exact id missing)", ""]
        for label, key, limit in (
            ("docker", "docker", 20),
            ("kubernetes", "kubernetes", 15),
        ):
            checkov = set(snapshot.get(key, []))
            missing = sorted(checkov - ours.get(key, set()))
            lines.append(f"### {label} ({len(missing)} missing)")
            lines.append("")
            if not missing:
                lines.append("_None._")
            else:
                lines.append(", ".join(f"`{m}`" for m in missing[:limit]))
                if len(missing) > limit:
                    lines.append(f"… and {len(missing) - limit} more.")
            lines.append("")

    lines += [
        "## Known result / id divergences",
        "",
        "| Topic | Detail |",
        "| --- | --- |",
    ]
    for cid, detail in DIVERGENCES:
        lines.append(f"| `{cid}` | {detail} |")
    lines += [
        "| Unknown interpolations | rustmaninoff never fails the process on `Unknown`; Checkov may guess or fail differently. |",
        "| Graph (`CKV2_*`) | First-wave AWS only; not full Checkov graph pack. |",
        "| Helm / plan JSON / secrets / CVE | Intentional product gaps (see ROADMAP). |",
        "",
        "## Refresh",
        "",
        "```sh",
        "python3 scripts/fetch_checkov_ids.py   # refresh tools/checkov-ids/snapshot.json",
        "python3 scripts/coverage_inventory.py -o docs/fidelity.md",
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-o", "--output", type=Path, help="Write Markdown here")
    args = parser.parse_args()
    md = render_markdown(policy_ids(), load_snapshot())
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(md + "\n")
    else:
        print(md)


if __name__ == "__main__":
    main()
